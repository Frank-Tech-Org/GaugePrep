// Usage: node apps/web/scripts/build-tokens.mjs [--check]
// Generates src/styles/tokens.css from the brand tokens.json; --check fails when the file differs.
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import process from "node:process";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const SOURCE = join(here, "../../../docs/design/brand/tokens.json");
const TARGET = join(here, "../src/styles/tokens.css");

const resolve = (value) => value.replace(/\{([\w-]+)\}/g, "var(--$1)");
const lines = (decls, indent) =>
  decls.map(([name, value]) => `${indent}--${name}: ${value};`).join("\n");

export function renderTokens(tokens) {
  const themed = tokens.color.tokens.filter((t) => typeof t.value === "object");
  const fixed = tokens.color.tokens.filter((t) => typeof t.value === "string");
  const pick = (theme) => themed.map((t) => [t.name, resolve(t.value[theme])]);
  const shadow = tokens.shadow.tokens.map((t) => [t.name, t.value]);
  const plain = [
    ...tokens.spacing.tokens,
    ...tokens.radius.tokens,
    ...tokens.size.tokens,
  ].map((t) => [t.name, t.value]);
  const type = tokens.type.groups.flatMap((g) =>
    g.styles.flatMap((s) => [
      [`type-${s.name}-size`, s.fontSize],
      [`type-${s.name}-line`, s.lineHeight],
      [`type-${s.name}-weight`, String(s.fontWeight)],
      ...(s.letterSpacing
        ? [[`type-${s.name}-tracking`, s.letterSpacing]]
        : []),
    ]),
  );
  const families = Object.entries(tokens.type.families).map(([k, v]) => [
    `font-${k}`,
    v,
  ]);
  const dark = pick("dark");
  const darkShadow = tokens.shadow.tokens.map((t) => [t.name, t.value.dark]);
  const light = [...pick("light"), ["shadow-card", shadow[0][1].light]];
  const css = `/* Generated by scripts/build-tokens.mjs from docs/design/brand/tokens.json. Do not edit. */
:root {
  color-scheme: light;
${lines(
  fixed.map((t) => [t.name, resolve(t.value)]),
  "  ",
)}
${lines(light, "  ")}
${lines(plain, "  ")}
${lines(families, "  ")}
${lines(type, "  ")}
}
@media (prefers-color-scheme: dark) {
  :root:not([data-theme="light"]) {
    color-scheme: dark;
${lines([...dark, ...darkShadow], "    ")}
  }
}
:root[data-theme="dark"] {
  color-scheme: dark;
${lines([...dark, ...darkShadow], "  ")}
}
`;
  return css.replace(/#[0-9a-f]{3,8}\b/gi, (hex) => hex.toLowerCase());
}

function main() {
  const css = renderTokens(JSON.parse(readFileSync(SOURCE, "utf8")));
  if (process.argv.includes("--check")) {
    let current = "";
    try {
      current = readFileSync(TARGET, "utf8");
    } catch {
      // a missing file counts as different
    }
    if (current !== css) {
      process.stderr.write(
        "tokens.css is out of date with the brand tokens. Run: pnpm --filter @gaugeprep/web tokens\n",
      );
      process.exit(1);
    }
    return;
  }
  writeFileSync(TARGET, css);
}

if (process.argv[1] === fileURLToPath(import.meta.url)) main();
